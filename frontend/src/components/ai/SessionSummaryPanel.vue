<template>
  <div class="bg-white rounded-xl border border-slate-200 p-5 space-y-4">
    <div class="flex items-center justify-between">
      <div>
        <h3 class="text-sm font-bold text-slate-900">AI session summary</h3>
        <p class="text-[11px] text-slate-500">Paste your own notes. Personal details are removed before any AI call, and nothing is saved unless you confirm.</p>
      </div>
    </div>

    <div v-if="error" class="p-2.5 rounded bg-rose-50 border border-rose-200 text-xs text-rose-700">{{ error }}</div>

    <div class="grid sm:grid-cols-2 gap-3">
      <label class="text-xs">Mentorship
        <select v-model="pairId" @change="loadMeetings" class="mt-1 w-full border border-slate-300 rounded p-1.5 text-xs">
          <option v-for="p in pairs" :key="p.id" :value="p.id">#{{ p.id }} · {{ p.status.toLowerCase() }}</option>
        </select>
      </label>
      <label class="text-xs">Meeting
        <select v-model="meetingId" class="mt-1 w-full border border-slate-300 rounded p-1.5 text-xs">
          <option v-for="m in meetings" :key="m.id" :value="m.id">{{ m.session_date }} · {{ m.duration_minutes }} min · {{ m.status.toLowerCase() }}</option>
        </select>
      </label>
    </div>

    <textarea v-model="notes" rows="6" placeholder="e.g. Discussed SQL prep. - Practise twenty joins - Update the resume"
              class="w-full text-xs p-2.5 rounded-lg border border-slate-300"></textarea>
    <button @click="generate" :disabled="loading || !meetingId || notes.trim().length < 20"
            class="px-4 py-2 text-xs font-semibold rounded-lg bg-blue-600 text-white disabled:opacity-50">
      {{ loading ? 'Generating draft…' : 'Generate draft' }}
    </button>

    <div v-if="draft" class="p-4 rounded-lg bg-slate-50 border border-slate-200 space-y-3">
      <div class="flex flex-wrap gap-2 text-[10px]">
        <span class="px-2 py-0.5 rounded font-semibold" :class="draft.fallback ? 'bg-amber-100 text-amber-800' : 'bg-emerald-100 text-emerald-800'">
          {{ draft.fallback ? 'Extractive fallback' : `Generated by ${draft.provider}` }}
        </span>
        <span class="px-2 py-0.5 rounded bg-slate-200 text-slate-700">prompt {{ draft.prompt_version }}</span>
        <span class="px-2 py-0.5 rounded bg-slate-200 text-slate-700">removed: {{ removed }}</span>
      </div>
      <label class="block text-xs font-semibold">Summary (edit before saving)
        <textarea v-model="draft.summary" rows="4" class="mt-1 w-full text-xs p-2 rounded border border-slate-300 font-normal"></textarea>
      </label>
      <div class="text-xs font-semibold">Action items</div>
      <div v-for="(a, i) in draft.action_items" :key="i" class="flex gap-2">
        <input v-model="draft.action_items[i]" class="flex-1 text-xs p-1.5 rounded border border-slate-300" />
        <button @click="draft.action_items.splice(i, 1)" class="text-xs text-slate-400 hover:text-rose-600">remove</button>
      </div>
      <div class="flex gap-2 pt-1">
        <button @click="confirm" class="px-3 py-1.5 text-xs rounded bg-slate-800 text-white">Confirm</button>
        <button @click="draft = null; saved = ''" class="px-3 py-1.5 text-xs rounded border border-slate-300">Discard</button>
      </div>
      <div v-if="saved" class="text-[11px] text-slate-600">{{ saved }}</div>
    </div>
  </div>
</template>

<script setup>
import { ref, computed, onMounted } from 'vue';
import { Sangam } from '../../api/client';

const pairs = ref([]);
const meetings = ref([]);
const pairId = ref(null);
const meetingId = ref(null);
const notes = ref('');
const draft = ref(null);
const loading = ref(false);
const error = ref('');
const saved = ref('');

const removed = computed(() => Object.entries(draft.value?.pii_removed || {}).filter(([, n]) => n).map(([k, n]) => `${n} ${k.replace('_', ' ')}`).join(', ') || 'nothing');

async function loadMeetings() {
  meetings.value = pairId.value ? await Sangam.meetings(pairId.value) : [];
  meetingId.value = meetings.value[0]?.id || null;
}

async function generate() {
  error.value = ''; saved.value = ''; loading.value = true;
  try {
    draft.value = await Sangam.summarise(pairId.value, meetingId.value, notes.value);
  } catch (e) {
    error.value = e.status === 429 ? 'Hourly summary limit reached. Try again later.' : e.message;
  } finally {
    loading.value = false;
  }
}

async function confirm() {
  const r = await Sangam.confirmSummary(pairId.value, meetingId.value,
    { summary: draft.value.summary, action_items: draft.value.action_items, prompt_version: draft.value.prompt_version });
  saved.value = r.stored ? `Saved (id ${r.id}).` : r.detail;
}

onMounted(async () => {
  try {
    pairs.value = (await Sangam.mentorships()).filter((p) => p.status === 'ACTIVE');
    pairId.value = pairs.value[0]?.id || null;
    await loadMeetings();
  } catch (e) {
    error.value = `Could not load mentorships: ${e.message}`;
  }
});
</script>
